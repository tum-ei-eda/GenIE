#!/usr/bin/env python3
"""Stage guides and generated references, then build the documentation strictly."""
import argparse
import html
import inspect
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]


def code(value):
    """Use HTML code so pipes/backticks in defaults cannot break a Markdown table."""
    return "<code>" + html.escape(str(value)).replace("|", "&#124;").replace("\n", " ") + "</code>"


def variables_table(variables):
    lines = ["| Variable | Type | Default | Description |", "| --- | --- | --- | --- |"]
    for var in variables:
        description = " ".join(var.description.split()).replace("|", "\\|")
        lines.append(f"| {code(var.name)} | {code(var.type)} | {code(var.default)} | {description} |")
    return "\n".join(lines) + "\n"


def generate_reference(source):
    from genie.config.flow import genie_flow_common_variables
    from genie.flows import GenIEFlow
    from genie.steps import GenIEStep

    reference = source / "reference"
    reference.mkdir()
    flows = ["# Registered flows", "", "Generated from `GenIEFlow.factory`; step order is execution order.", ""]
    for name in sorted(GenIEFlow.factory.list()):
        flow = GenIEFlow.factory.get(name)
        flows += [f"## {name}", "", f"Implementation: {code(flow.__module__ + '.' + flow.__name__)}", ""]
        flows += [f"{i}. {code(step.id)}" for i, step in enumerate(flow.Steps, 1)]
        flows.append("")
    (reference / "flows.md").write_text("\n".join(flows), encoding="utf-8")

    steps = ["# Registered steps", "", "Registration does not prove external tool availability or validation.", ""]
    for name in sorted(GenIEStep.factory.list()):
        step = GenIEStep.factory.get(name)
        steps += [f"## {name}", "", f"Implementation: {code(step.__module__ + '.' + step.__name__)}", ""]
        description = inspect.getdoc(step)
        if description:
            # Existing step docstrings mix rST and Markdown; preserve them literally.
            steps += ["````text", description, "````", ""]
        steps += [variables_table(step.config_vars), ""]
    (reference / "steps.md").write_text("\n".join(steps), encoding="utf-8")
    (reference / "configuration.md").write_text(
        "# Common configuration\n\nGenerated from `genie_flow_common_variables`. "
        "Step-specific options are listed in the [step reference](steps.md). "
        "`None` denotes the Python default; required values are validated when loading a configuration.\n\n"
        + variables_table(genie_flow_common_variables), encoding="utf-8")

    cli = ["# Command-line reference", "", "Generated by invoking each command with `--help`.", ""]
    for module in ("genie", "genie.config", "genie.state", "genie.steps", "genie.prototype", "genie.monitor"):
        result = subprocess.run([sys.executable, "-m", module, "--help"], cwd=ROOT,
                                check=True, capture_output=True, text=True)
        cli += [f"## python -m {module}", "", "````text", result.stdout.strip(), "````", ""]
    (reference / "cli.md").write_text("\n".join(cli), encoding="utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--builder", choices=("html", "linkcheck"), default="html")
    parser.add_argument("--output-dir", type=Path, default=ROOT / "docs/_build/html")
    args = parser.parse_args()
    output = args.output_dir.resolve()
    # A fresh temporary source tree prevents stale generated reference pages.
    # Mirror repository paths so existing relative links work without rewriting guides.
    with tempfile.TemporaryDirectory(prefix="genie-docs-") as directory:
        source = Path(directory)
        shutil.copytree(ROOT / "docs", source / "docs",
                        ignore=shutil.ignore_patterns("_build", "__pycache__"))
        shutil.copy2(ROOT / "PROGRESS.md", source / "PROGRESS.md")
        shutil.copytree(ROOT / "cfg", source / "cfg")
        shutil.copy2(ROOT / "docs/index.md", source / "index.md")
        if (source / "docs/figures/README.md").exists():
            with (source / "index.md").open("a", encoding="utf-8") as index:
                index.write("\n```{toctree}\n:caption: Figures\n\ndocs/figures/README\n```\n")
        generate_reference(source)
        subprocess.run([sys.executable, "-m", "sphinx", "-b", args.builder,
                        "-W", "--keep-going", "-E", "-a", "-c", str(ROOT / "docs"),
                        str(source), str(output)], check=True, cwd=ROOT)
    if args.builder == "html":
        (output / ".nojekyll").touch()
    print(f"Documentation written to {output}")


if __name__ == "__main__":
    main()
